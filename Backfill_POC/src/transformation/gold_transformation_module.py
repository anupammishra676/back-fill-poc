from datetime import datetime

from pyspark.sql import functions as F

from src.config.config_module import CONFIG
from src.config.pipeline_config import PipelineConfig
from src.services.incremental_service import IncrementalService
from src.utils.logging_utils_module import ApplicationLogger
from src.utils.spark_utils_module import SparkUtils
from src.audit.audit_logger_module import AuditLogger


class GoldTransformation:

    """
    Builds Gold business aggregates from Silver data.

    Supported modes:
        INITIAL
        INCREMENTAL
        BACKFILL

    Gold tables:
        1. gold_daily_revenue
        2. gold_product_sales
    """

    VALID_MODES = {
        "INITIAL",
        "INCREMENTAL",
        "BACKFILL"
    }

    LAYER_DAILY_REVENUE = "GOLD_DAILY_REVENUE"
    LAYER_PRODUCT_SALES = "GOLD_PRODUCT_SALES"

    def __init__(self, spark):

        self.spark = spark

        self.logger = ApplicationLogger.get_logger(
            self.__class__.__name__
        )

        self.audit_logger = AuditLogger(spark)

        self.pipeline_name = CONFIG.pipeline_name

        self.pipeline_config = PipelineConfig(
            self.spark
        )

        self.incremental_service = IncrementalService(
            self.spark
        )

    # =========================================================
    # PUBLIC METHOD
    # =========================================================

    def run(
        self,
        mode: str,
        run_id: str = None,
        request_id=None,
        start_date=None,
        end_date=None
    ):

        mode = mode.upper()

        if not run_id:
            raise ValueError(
                "run_id is required. "
                "It must be generated by the workflow/orchestrator."
            )

        start_time = datetime.now()

        self.logger.info(
            f"Starting Gold transformation | "
            f"run_id={run_id} | "
            f"request_id={request_id} | "
            f"mode={mode}"
        )

        records_read = 0

        try:

            # -------------------------------------------------
            # 1. Validate parameters
            # -------------------------------------------------

            self._validate_parameters(
                mode,
                start_date,
                end_date
            )

            # -------------------------------------------------
            # 2. Resolve configurations
            # -------------------------------------------------

            daily_config = self._get_pipeline_config(
                self.LAYER_DAILY_REVENUE
            )

            product_config = self._get_pipeline_config(
                self.LAYER_PRODUCT_SALES
            )

            # -------------------------------------------------
            # 3. Validate tables
            # -------------------------------------------------

            self._validate_tables(
                daily_config,
                product_config
            )

            # -------------------------------------------------
            # 4. Resolve processing window
            # -------------------------------------------------

            start_date, end_date = (
                self._resolve_processing_window(
                    daily_config,
                    mode,
                    start_date,
                    end_date
                )
            )

            # -------------------------------------------------
            # 5. Handle no incremental data
            # -------------------------------------------------

            if mode == "INCREMENTAL" and start_date is None:

                self.logger.info(
                    "No incremental data to process | "
                    f"run_id={run_id}"
                )

                self.audit_logger.log_run(
                    run_id=run_id,
                    request_id=request_id,
                    pipeline_name=self.pipeline_name,
                    layer="GOLD",
                    operation=mode,
                    status="SUCCESS",
                    start_time=start_time,
                    end_time=datetime.now(),
                    records_read=0,
                    records_written=0,
                    processing_start_date=None,
                    processing_end_date=None,
                    parameters={
                        "mode": mode,
                        "start_date": None,
                        "end_date": None
                    }
                )

                return {
                    "run_id": run_id,
                    "status": "NO_DATA",
                    "records_read": 0,
                    "daily_revenue_records": 0,
                    "product_sales_records": 0
                }

            # -------------------------------------------------
            # 6. Audit STARTED
            # -------------------------------------------------

            self.audit_logger.log_run(
                run_id=run_id,
                request_id=request_id,
                pipeline_name=self.pipeline_name,
                layer="GOLD",
                operation=mode,
                status="STARTED",
                start_time=start_time,
                processing_start_date=start_date,
                processing_end_date=end_date,
                parameters={
                    "mode": mode,
                    "start_date": (
                        str(start_date)
                        if start_date else None
                    ),
                    "end_date": (
                        str(end_date)
                        if end_date else None
                    )
                }
            )

            # -------------------------------------------------
            # 7. Read Silver
            # -------------------------------------------------

            silver_df = self._read_silver(
                daily_config,
                mode,
                start_date,
                end_date
            )

            records_read = silver_df.count()

            self.logger.info(
                f"Silver records identified | "
                f"run_id={run_id} | "
                f"records_read={records_read}"
            )

            # -------------------------------------------------
            # 8. Build aggregations
            # -------------------------------------------------

            daily_revenue_df = (
                self._build_daily_revenue(
                    silver_df,
                    run_id
                )
            )

            product_sales_df = (
                self._build_product_sales(
                    silver_df,
                    run_id
                )
            )

            # -------------------------------------------------
            # 9. Replace affected Gold data
            # -------------------------------------------------

            self._replace_processing_window(
                daily_config,
                product_config,
                mode,
                start_date,
                end_date
            )

            # -------------------------------------------------
            # 10. Write Gold
            # -------------------------------------------------

            daily_count = self._write_table(
                daily_revenue_df,
                daily_config.target_table
            )

            product_count = self._write_table(
                product_sales_df,
                product_config.target_table
            )

            total_written = (
                daily_count + product_count
            )

            end_time = datetime.now()

            # -------------------------------------------------
            # 11. Audit SUCCESS
            # -------------------------------------------------

            self.audit_logger.log_run(
                run_id=run_id,
                request_id=request_id,
                pipeline_name=self.pipeline_name,
                layer="GOLD",
                operation=mode,
                status="SUCCESS",
                start_time=start_time,
                end_time=end_time,
                records_read=records_read,
                records_written=total_written,
                processing_start_date=start_date,
                processing_end_date=end_date,
                parameters={
                    "mode": mode,
                    "start_date": (
                        str(start_date)
                        if start_date else None
                    ),
                    "end_date": (
                        str(end_date)
                        if end_date else None
                    ),
                    "daily_revenue_records": daily_count,
                    "product_sales_records": product_count
                }
            )

            self.logger.info(
                "Gold transformation completed | "
                f"run_id={run_id} | "
                f"daily_revenue={daily_count} | "
                f"product_sales={product_count}"
            )

            return {
                "run_id": run_id,
                "status": "SUCCESS",
                "records_read": records_read,
                "daily_revenue_records": daily_count,
                "product_sales_records": product_count
            }

        except Exception as exc:

            end_time = datetime.now()

            self.logger.exception(
                f"Gold transformation failed | "
                f"run_id={run_id} | "
                f"request_id={request_id} | "
                f"error={str(exc)}"
            )

            try:

                self.audit_logger.log_run(
                    run_id=run_id,
                    request_id=request_id,
                    pipeline_name=self.pipeline_name,
                    layer="GOLD",
                    operation=mode,
                    status="FAILED",
                    start_time=start_time,
                    end_time=end_time,
                    records_read=records_read,
                    processing_start_date=start_date,
                    processing_end_date=end_date,
                    parameters={
                        "mode": mode,
                        "start_date": (
                            str(start_date)
                            if start_date else None
                        ),
                        "end_date": (
                            str(end_date)
                            if end_date else None
                        )
                    },
                    error_message=str(exc)
                )

            except Exception:

                self.logger.exception(
                    "Failed to write Gold FAILED audit record."
                )

            raise

    # =========================================================
    # CONFIGURATION
    # =========================================================

    def _get_pipeline_config(self, layer):

        config = self.pipeline_config.get_config(
            pipeline_name=self.pipeline_name,
            layer=layer
        )

        self.logger.info(
            "Gold pipeline configuration resolved | "
            f"layer={layer} | "
            f"source_table={config.source_table} | "
            f"target_table={config.target_table} | "
            f"partition_column={config.partition_column}"
        )

        return config

    # =========================================================
    # VALIDATION
    # =========================================================

    def _validate_parameters(
        self,
        mode,
        start_date,
        end_date
    ):

        if mode not in self.VALID_MODES:

            raise ValueError(
                f"Invalid mode: {mode}. "
                f"Allowed modes: {self.VALID_MODES}"
            )

        # Only BACKFILL requires explicit dates
        if mode == "BACKFILL":

            if start_date is None or end_date is None:

                raise ValueError(
                    "BACKFILL requires start_date and end_date."
                )

        # INITIAL ignores dates
        if mode == "INITIAL":

            if start_date is not None or end_date is not None:

                self.logger.warning(
                    "INITIAL mode ignores start_date/end_date."
                )

        # INCREMENTAL dates are resolved automatically

        if start_date is not None and end_date is not None:

            if start_date > end_date:

                raise ValueError(
                    "start_date cannot be greater than end_date."
                )

    # =========================================================
    # PROCESSING WINDOW
    # =========================================================

    def _resolve_processing_window(
        self,
        config,
        mode,
        start_date=None,
        end_date=None
    ):

        if mode == "INITIAL":

            self.logger.info(
                "INITIAL mode: no processing window required."
            )

            return None, None

        if mode == "BACKFILL":

            self.logger.info(
                "BACKFILL processing window resolved | "
                f"start_date={start_date} | "
                f"end_date={end_date}"
            )

            return start_date, end_date

        if mode == "INCREMENTAL":

            window = (
                self.incremental_service
                .get_incremental_window(
                    pipeline_name=self.pipeline_name,
                    layer=config.layer
                )
            )

            if not window.has_data:

                self.logger.info(
                    "No incremental processing window available | "
                    f"layer={config.layer}"
                )

                return None, None

            self.logger.info(
                "Incremental processing window resolved | "
                f"start_date={window.start_date} | "
                f"end_date={window.end_date}"
            )

            return (
                window.start_date,
                window.end_date
            )

        raise ValueError(
            f"Unsupported processing mode: {mode}"
        )

    # =========================================================
    # TABLE VALIDATION
    # =========================================================

    def _validate_tables(
        self,
        daily_config,
        product_config
    ):

        tables = [
            daily_config.source_table,
            daily_config.target_table,
            product_config.target_table
        ]

        for table in tables:

            if not SparkUtils.validate_table_exists(
                self.spark,
                table
            ):

                raise ValueError(
                    f"Required table does not exist: {table}"
                )

        self.logger.info(
            "Silver and Gold tables validated."
        )

    # =========================================================
    # READ SILVER
    # =========================================================

    def _read_silver(
        self,
        config,
        mode,
        start_date,
        end_date
    ):

        df = self.spark.table(
            config.source_table
        )

        if mode == "INITIAL":

            self.logger.info(
                "INITIAL mode: reading complete Silver dataset."
            )

            return df

        partition_column = (config.source_partition_column)

        if not partition_column:

            raise ValueError(
                "Partition column is required for "
                f"{mode} processing."
            )

        self.logger.info(
            f"{mode}: reading Silver data | "
            f"partition_column={partition_column} | "
            f"start_date={start_date} | "
            f"end_date={end_date}"
        )

        return df.filter(
            (F.col(partition_column) >= F.lit(start_date))
            & (
                F.col(partition_column)
                <= F.lit(end_date)
            )
        )

    # =========================================================
    # DAILY REVENUE
    # =========================================================

    def _build_daily_revenue(
        self,
        df,
        run_id
    ):

        self.logger.info(
            "Building daily revenue aggregation."
        )

        return (
            df
            .groupBy("order_date")
            .agg(
                F.countDistinct("order_id")
                .alias("total_orders"),

                F.sum("quantity")
                .cast("long")
                .alias("total_units"),

                F.sum("gross_amount")
                .cast("decimal(18,2)")
                .alias("gross_revenue"),

                F.sum("discount_amount")
                .cast("decimal(18,2)")
                .alias("discount_amount"),

                F.sum("net_amount")
                .cast("decimal(18,2)")
                .alias("net_revenue")
            )
            .withColumn(
                "processing_timestamp",
                F.current_timestamp()
            )
            .withColumn(
                "run_id",
                F.lit(run_id)
            )
            .select(
                F.col("order_date").alias("business_date"),
                "total_orders",
                "total_units",
                "gross_revenue",
                "discount_amount",
                "net_revenue",
                "processing_timestamp",
                "run_id"
            )
        )

    # =========================================================
    # PRODUCT SALES
    # =========================================================

    def _build_product_sales(
        self,
        df,
        run_id
    ):

        self.logger.info(
            "Building product sales aggregation."
        )

        return (
            df
            .groupBy("order_date", "product_category")
            .agg(
                F.countDistinct("order_id")
                .alias("total_orders"),

                F.sum("quantity")
                .cast("long")
                .alias("total_units"),

                F.sum("gross_amount")
                .cast("decimal(18,2)")
                .alias("gross_revenue"),

                F.sum("discount_amount")
                .cast("decimal(18,2)")
                .alias("discount_amount"),

                F.sum("net_amount")
                .cast("decimal(18,2)")
                .alias("net_revenue")
            )
            .withColumn(
                "processing_timestamp",
                F.current_timestamp()
            )
            .withColumn(
                "run_id",
                F.lit(run_id)
            )
            .select(
                F.col("order_date").alias("business_date"),
                "product_category",
                "total_orders",
                "total_units",
                "gross_revenue",
                "discount_amount",
                "net_revenue",
                "processing_timestamp",
                "run_id"
            )
        )

    # =========================================================
    # IDEMPOTENT REPLACEMENT
    # =========================================================

    def _replace_processing_window(
        self,
        daily_config,
        product_config,
        mode,
        start_date,
        end_date
    ):

        if mode == "INITIAL":

            self.logger.info(
                "INITIAL mode: clearing Gold tables."
            )

            self.spark.sql(
                f"DELETE FROM "
                f"{daily_config.target_table}"
            )

            self.spark.sql(
                f"DELETE FROM "
                f"{product_config.target_table}"
            )

            return

        daily_partition = (
            daily_config.target_partition_column
        )

        product_partition = (
            product_config.target_partition_column
        )

        self.logger.info(
            "Replacing Gold processing window | "
            f"start_date={start_date} | "
            f"end_date={end_date}"
        )

        self.spark.sql(
            f"""
            DELETE FROM {daily_config.target_table}
            WHERE {daily_partition} >= DATE('{start_date}')
              AND {daily_partition} <= DATE('{end_date}')
            """
        )

        self.spark.sql(
            f"""
            DELETE FROM {product_config.target_table}
            WHERE {product_partition} >= DATE('{start_date}')
              AND {product_partition} <= DATE('{end_date}')
            """
        )

    # =========================================================
    # WRITE
    # =========================================================

    def _write_table(
        self,
        df,
        table_name
    ):

        record_count = df.count()

        (
            df.write
            .format("delta")
            .mode("append")
            .saveAsTable(table_name)
        )

        self.logger.info(
            "Gold table written | "
            f"table={table_name} | "
            f"records={record_count}"
        )

        return record_count