from datetime import datetime

from pyspark.sql import functions as F

from src.config.config_module import CONFIG
from src.config.pipeline_config import PipelineConfig
from src.services.incremental_service import IncrementalService
from src.utils.logging_utils_module import ApplicationLogger
from src.utils.spark_utils_module import SparkUtils
from src.audit.audit_logger_module import AuditLogger


class SilverTransformation:

    """
    Transforms Bronze data into the Silver layer.

    Supported modes:
        INITIAL
        INCREMENTAL
        BACKFILL

    Processing is idempotent for the requested date window.
    """

    VALID_MODES = {
        "INITIAL",
        "INCREMENTAL",
        "BACKFILL"
    }

    LAYER = "SILVER"

    def __init__(self, spark):

        self.spark = spark

        self.logger = ApplicationLogger.get_logger(
            self.__class__.__name__
        )

        self.audit_logger = AuditLogger(spark)

        self.pipeline_name = CONFIG.pipeline_name

        # Configuration
        self.pipeline_config = PipelineConfig(
            self.spark
        )

        # Incremental window calculation
        self.incremental_service = IncrementalService(
            self.spark
        )

    # =========================================================
    # PUBLIC METHOD
    # =========================================================

    def run(
        self,
        mode: str,
        run_id: str = None,
        request_id=None,
        start_date=None,
        end_date=None
    ):

        mode = mode.upper()

        if not run_id:
            raise ValueError(
                "run_id is required. "
                "It must be generated by the workflow/orchestrator."
            )

        start_time = datetime.now()

        self.logger.info(
            f"Starting Silver transformation | "
            f"run_id={run_id} | "
            f"request_id={request_id} | "
            f"mode={mode}"
        )

        records_read = 0
        records_written = 0

        try:

            # -------------------------------------------------
            # 1. Validate parameters
            # -------------------------------------------------

            self._validate_parameters(
                mode,
                start_date,
                end_date
            )

            # -------------------------------------------------
            # 2. Resolve pipeline configuration
            # -------------------------------------------------

            config = self._get_pipeline_config()

            # -------------------------------------------------
            # 3. Validate tables
            # -------------------------------------------------

            self._validate_tables(config)

            # -------------------------------------------------
            # 4. Resolve processing window
            # -------------------------------------------------

            start_date, end_date = (
                self._resolve_processing_window(
                    config,
                    mode,
                    start_date,
                    end_date
                )
            )

            # -------------------------------------------------
            # 5. Handle no incremental data
            # -------------------------------------------------

            if mode == "INCREMENTAL" and start_date is None:

                self.logger.info(
                    "No incremental data to process | "
                    f"run_id={run_id}"
                )

                self.audit_logger.log_run(
                    run_id=run_id,
                    request_id=request_id,
                    pipeline_name=self.pipeline_name,
                    layer=self.LAYER,
                    operation=mode,
                    status="SUCCESS",
                    start_time=start_time,
                    end_time=datetime.now(),
                    records_read=0,
                    records_written=0,
                    processing_start_date=None,
                    processing_end_date=None,
                    parameters={
                        "mode": mode,
                        "start_date": None,
                        "end_date": None
                    }
                )

                return {
                    "run_id": run_id,
                    "status": "NO_DATA",
                    "records_read": 0,
                    "records_written": 0
                }

            # -------------------------------------------------
            # 6. Audit STARTED
            # -------------------------------------------------

            self.audit_logger.log_run(
                run_id=run_id,
                request_id=request_id,
                pipeline_name=self.pipeline_name,
                layer=self.LAYER,
                operation=mode,
                status="STARTED",
                start_time=start_time,
                processing_start_date=start_date,
                processing_end_date=end_date,
                parameters={
                    "mode": mode,
                    "start_date": (
                        str(start_date)
                        if start_date else None
                    ),
                    "end_date": (
                        str(end_date)
                        if end_date else None
                    )
                }
            )

            # -------------------------------------------------
            # 7. Read Bronze
            # -------------------------------------------------

            bronze_df = self._read_bronze(
                config,
                mode,
                start_date,
                end_date
            )

            records_read = bronze_df.count()

            self.logger.info(
                f"Bronze records identified | "
                f"run_id={run_id} | "
                f"records_read={records_read}"
            )

            # -------------------------------------------------
            # 8. Validate Bronze data
            # -------------------------------------------------

            bronze_df = self._validate_data(
                bronze_df
            )

            # -------------------------------------------------
            # 9. Apply transformations
            # -------------------------------------------------

            silver_df = self._transform(
                bronze_df
            )

            # -------------------------------------------------
            # 10. Replace processing window
            # -------------------------------------------------

            self._replace_processing_window(
                config,
                mode,
                start_date,
                end_date
            )

            # -------------------------------------------------
            # 11. Write Silver
            # -------------------------------------------------

            records_written = self._write_silver(
                silver_df,
                config,
                run_id
            )

            end_time = datetime.now()

            # -------------------------------------------------
            # 12. Audit SUCCESS
            # -------------------------------------------------

            self.audit_logger.log_run(
                run_id=run_id,
                request_id=request_id,
                pipeline_name=self.pipeline_name,
                layer=self.LAYER,
                operation=mode,
                status="SUCCESS",
                start_time=start_time,
                end_time=end_time,
                records_read=records_read,
                records_written=records_written,
                processing_start_date=start_date,
                processing_end_date=end_date,
                parameters={
                    "mode": mode,
                    "start_date": (
                        str(start_date)
                        if start_date else None
                    ),
                    "end_date": (
                        str(end_date)
                        if end_date else None
                    )
                }
            )

            self.logger.info(
                f"Silver transformation completed | "
                f"run_id={run_id} | "
                f"records_written={records_written}"
            )

            return {
                "run_id": run_id,
                "status": "SUCCESS",
                "records_read": records_read,
                "records_written": records_written
            }

        except Exception as exc:

            end_time = datetime.now()

            self.logger.exception(
                f"Silver transformation failed | "
                f"run_id={run_id} | "
                f"request_id={request_id} | "
                f"error={str(exc)}"
            )

            try:

                self.audit_logger.log_run(
                    run_id=run_id,
                    request_id=request_id,
                    pipeline_name=self.pipeline_name,
                    layer=self.LAYER,
                    operation=mode,
                    status="FAILED",
                    start_time=start_time,
                    end_time=end_time,
                    records_read=records_read,
                    records_written=records_written,
                    processing_start_date=start_date,
                    processing_end_date=end_date,
                    parameters={
                        "mode": mode,
                        "start_date": (
                            str(start_date)
                            if start_date else None
                        ),
                        "end_date": (
                            str(end_date)
                            if end_date else None
                        )
                    },
                    error_message=str(exc)
                )

            except Exception:

                self.logger.exception(
                    "Failed to write Silver FAILED audit record."
                )

            raise

    # =========================================================
    # CONFIGURATION
    # =========================================================

    def _get_pipeline_config(self):

        config = self.pipeline_config.get_config(
            pipeline_name=self.pipeline_name,
            layer=self.LAYER
        )

        self.logger.info(
            "Silver pipeline configuration resolved | "
            f"source_table={config.source_table} | "
            f"target_table={config.target_table} | "
            f"partition_column={config.partition_column} | "
            f"incremental_strategy={config.incremental_strategy}"
        )

        return config

    # =========================================================
    # VALIDATION
    # =========================================================

    def _validate_parameters(
        self,
        mode,
        start_date,
        end_date
    ):

        if mode not in self.VALID_MODES:

            raise ValueError(
                f"Invalid mode: {mode}. "
                f"Allowed modes: {self.VALID_MODES}"
            )

        # BACKFILL requires explicit dates
        if mode == "BACKFILL":

            if start_date is None or end_date is None:

                raise ValueError(
                    "BACKFILL requires start_date and end_date."
                )

        # INITIAL does not require dates
        if mode == "INITIAL":

            if start_date is not None or end_date is not None:

                self.logger.warning(
                    "INITIAL mode ignores start_date/end_date."
                )

        # INCREMENTAL does NOT require dates.
        # IncrementalService determines them automatically.

        if start_date is not None and end_date is not None:

            if start_date > end_date:

                raise ValueError(
                    "start_date cannot be greater than end_date."
                )

    # =========================================================
    # PROCESSING WINDOW
    # =========================================================

    def _resolve_processing_window(
        self,
        config,
        mode,
        start_date=None,
        end_date=None
    ):

        if mode == "INITIAL":

            self.logger.info(
                "INITIAL mode: no processing window required."
            )

            return None, None

        if mode == "BACKFILL":

            self.logger.info(
                "BACKFILL processing window resolved | "
                f"start_date={start_date} | "
                f"end_date={end_date}"
            )

            return start_date, end_date

        if mode == "INCREMENTAL":

            window = (
                self.incremental_service
                .get_incremental_window(
                    pipeline_name=self.pipeline_name,
                    layer=self.LAYER
                )
            )

            if not window.has_data:

                self.logger.info(
                    "No incremental processing window available | "
                    f"pipeline_name={self.pipeline_name} | "
                    f"layer={self.LAYER}"
                )

                return None, None

            self.logger.info(
                "Incremental processing window resolved | "
                f"start_date={window.start_date} | "
                f"end_date={window.end_date}"
            )

            return (
                window.start_date,
                window.end_date
            )

        raise ValueError(
            f"Unsupported processing mode: {mode}"
        )

    # =========================================================
    # TABLE VALIDATION
    # =========================================================

    def _validate_tables(self, config):

        if not SparkUtils.validate_table_exists(
            self.spark,
            config.source_table
        ):

            raise ValueError(
                f"Bronze table does not exist: "
                f"{config.source_table}"
            )

        if not SparkUtils.validate_table_exists(
            self.spark,
            config.target_table
        ):

            raise ValueError(
                f"Silver table does not exist: "
                f"{config.target_table}"
            )

        self.logger.info(
            "Bronze and Silver tables validated | "
            f"source={config.source_table} | "
            f"target={config.target_table}"
        )

    # =========================================================
    # READ BRONZE
    # =========================================================

    def _read_bronze(
        self,
        config,
        mode,
        start_date,
        end_date
    ):

        df = self.spark.table(
            config.source_table
        )

        if mode == "INITIAL":

            self.logger.info(
                "INITIAL mode: reading complete Bronze dataset."
            )

            return df

        partition_column = config.partition_column

        if not partition_column:

            raise ValueError(
                "Partition column is required for "
                f"{mode} processing | "
                f"layer={config.layer}"
            )

        self.logger.info(
            f"{mode}: reading Bronze data | "
            f"partition_column={partition_column} | "
            f"start_date={start_date} | "
            f"end_date={end_date}"
        )

        return df.filter(
            (F.col(partition_column) >= F.lit(start_date))
            & (
                F.col(partition_column)
                <= F.lit(end_date)
            )
        )

    # =========================================================
    # DATA VALIDATION
    # =========================================================

    def _validate_data(self, df):

        self.logger.info(
            "Starting Silver data validation."
        )

        initial_count = df.count()

        df = df.filter(
            F.col("order_id").isNotNull()
            & F.col("order_date").isNotNull()
            & F.col("product_id").isNotNull()
        )

        df = df.filter(
            F.col("quantity") > 0
        )

        df = df.filter(
            F.col("unit_price") >= 0
        )

        df = df.filter(
            (F.col("discount_pct") >= 0)
            & (F.col("discount_pct") <= 100)
        )

        final_count = df.count()

        rejected_count = (
            initial_count - final_count
        )

        self.logger.info(
            f"Silver validation completed | "
            f"input={initial_count} | "
            f"valid={final_count} | "
            f"rejected={rejected_count}"
        )

        return df

    # =========================================================
    # TRANSFORMATION
    # =========================================================

    def _transform(self, df):

        self.logger.info(
            "Applying Silver business transformations."
        )

        df = (
            df
            .withColumn(
                "gross_amount",
                (
                    F.col("quantity")
                    * F.col("unit_price")
                ).cast("decimal(14,2)")
            )
            .withColumn(
                "discount_amount",
                (
                    F.col("quantity")
                    * F.col("unit_price")
                    * F.col("discount_pct")
                    / F.lit(100)
                ).cast("decimal(14,2)")
            )
            .withColumn(
                "net_amount",
                (
                    F.col("gross_amount")
                    - F.col("discount_amount")
                ).cast("decimal(14,2)")
            )
            .withColumn(
                "processing_timestamp",
                F.current_timestamp()
            )
        )

        return df.select(
            "order_id",
            "order_date",
            "customer_id",
            "product_id",
            "product_category",
            "quantity",
            "unit_price",
            "discount_pct",
            "gross_amount",
            "discount_amount",
            "net_amount",
            "payment_status",
            "order_status",
            "source_updated_at",
            "processing_timestamp"
        )

    # =========================================================
    # IDEMPOTENT REPLACEMENT
    # =========================================================

    def _replace_processing_window(
        self,
        config,
        mode,
        start_date,
        end_date
    ):

        target_table = config.target_table
        partition_column = config.partition_column

        if mode == "INITIAL":

            self.logger.info(
                "INITIAL mode: clearing existing Silver data | "
                f"target_table={target_table}"
            )

            self.spark.sql(
                f"DELETE FROM {target_table}"
            )

            return

        if not partition_column:

            raise ValueError(
                "Partition column is required for "
                f"{mode} replacement."
            )

        self.logger.info(
            "Replacing Silver processing window | "
            f"target_table={target_table} | "
            f"partition_column={partition_column} | "
            f"start_date={start_date} | "
            f"end_date={end_date}"
        )

        self.spark.sql(
            f"""
            DELETE FROM {target_table}
            WHERE {partition_column} >= DATE('{start_date}')
              AND {partition_column} <= DATE('{end_date}')
            """
        )

    # =========================================================
    # WRITE
    # =========================================================

    def _write_silver(
        self,
        df,
        config,
        run_id
    ):

        df = df.withColumn(
            "run_id",
            F.lit(run_id)
        )

        records_written = df.count()

        (
            df.write
            .format("delta")
            .mode("append")
            .saveAsTable(config.target_table)
        )

        self.logger.info(
            "Silver write completed | "
            f"run_id={run_id} | "
            f"target_table={config.target_table} | "
            f"records_written={records_written}"
        )

        return records_written