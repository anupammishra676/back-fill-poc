from datetime import datetime

from pyspark.sql.functions import col

from src.config.config_module import CONFIG
from src.config.pipeline_config import PipelineConfig
from src.services.incremental_service import IncrementalService
from src.utils.logging_utils_module import ApplicationLogger
from src.utils.spark_utils_module import SparkUtils
from src.audit.audit_logger_module import AuditLogger


class BronzeIngestion:

    """
    Handles ingestion from source system into Bronze.

    Supported modes:
        INITIAL
        INCREMENTAL
        BACKFILL

    Processing behavior is driven by pipeline_config.

    Mode behavior:

        INITIAL
            Reads the complete source table and replaces
            existing Bronze data.

        INCREMENTAL
            Determines the processing window automatically
            using IncrementalService and pipeline_config.

        BACKFILL
            Processes the explicitly supplied start_date
            and end_date.

    Bronze processing is idempotent for a given processing window.
    """

    VALID_MODES = {
        "INITIAL",
        "INCREMENTAL",
        "BACKFILL"
    }

    LAYER = "BRONZE"

    def __init__(self, spark):

        self.spark = spark

        self.logger = ApplicationLogger.get_logger(
            self.__class__.__name__
        )

        self.audit_logger = AuditLogger(spark)

        self.pipeline_name = CONFIG.pipeline_name

        self.pipeline_config = PipelineConfig(
            self.spark
        )

        self.incremental_service = IncrementalService(
            self.spark
        )

    # ---------------------------------------------------------
    # PUBLIC METHOD
    # ---------------------------------------------------------

    def run(
        self,
        mode: str,
        run_id: str = None,
        request_id=None,
        start_date=None,
        end_date=None
    ):
        """
        Execute Bronze ingestion.

        Parameters
        ----------
        mode : str
            INITIAL / INCREMENTAL / BACKFILL

        run_id : str
            Unique pipeline execution ID.

        request_id : str, optional
            Backfill request ID when execution is triggered
            through the backfill framework.

        start_date : date/string, optional
            Processing start date.
            Required only for BACKFILL.

        end_date : date/string, optional
            Processing end date.
            Required only for BACKFILL.

        Returns
        -------
        dict
            Execution result.
        """

        mode = mode.upper()

        if not run_id:
            raise ValueError(
                "run_id is required. "
                "It must be generated by the workflow/orchestrator."
            )

        start_time = datetime.now()

        self.logger.info(
            "Starting Bronze ingestion | "
            f"run_id={run_id} | "
            f"request_id={request_id} | "
            f"mode={mode}"
        )

        records_read = 0
        records_written = 0

        try:

            # -------------------------------------------------
            # 1. Validate parameters
            # -------------------------------------------------

            self._validate_parameters(
                mode=mode,
                start_date=start_date,
                end_date=end_date
            )

            # -------------------------------------------------
            # 2. Resolve pipeline configuration
            # -------------------------------------------------

            config = self._get_pipeline_config()

            # -------------------------------------------------
            # 3. Validate source and target tables
            # -------------------------------------------------

            self._validate_tables(config)

            # -------------------------------------------------
            # 4. Resolve processing window
            # -------------------------------------------------

            start_date, end_date = (
                self._resolve_processing_window(
                    config=config,
                    mode=mode,
                    start_date=start_date,
                    end_date=end_date
                )
            )

            # -------------------------------------------------
            # 5. Handle incremental NO_DATA
            # -------------------------------------------------

            if (
                mode == "INCREMENTAL"
                and start_date is None
            ):

                self.logger.info(
                    "No incremental data to process | "
                    f"run_id={run_id}"
                )

                self.audit_logger.log_run(
                    run_id=run_id,
                    request_id=request_id,
                    pipeline_name=self.pipeline_name,
                    layer=self.LAYER,
                    operation=mode,
                    status="SUCCESS",
                    start_time=start_time,
                    end_time=datetime.now(),
                    records_read=0,
                    records_written=0,
                    processing_start_date=None,
                    processing_end_date=None,
                    parameters={
                        "mode": mode,
                        "start_date": None,
                        "end_date": None
                    }
                )

                return {
                    "run_id": run_id,
                    "status": "NO_DATA",
                    "records_read": 0,
                    "records_written": 0
                }

            # -------------------------------------------------
            # 6. Audit STARTED
            # -------------------------------------------------

            self.audit_logger.log_run(
                run_id=run_id,
                request_id=request_id,
                pipeline_name=self.pipeline_name,
                layer=self.LAYER,
                operation=mode,
                status="STARTED",
                start_time=start_time,
                processing_start_date=start_date,
                processing_end_date=end_date,
                parameters={
                    "mode": mode,
                    "start_date": (
                        str(start_date)
                        if start_date else None
                    ),
                    "end_date": (
                        str(end_date)
                        if end_date else None
                    )
                }
            )

            # -------------------------------------------------
            # 7. Read source
            # -------------------------------------------------

            source_df = self._read_source(
                config=config,
                mode=mode,
                start_date=start_date,
                end_date=end_date
            )

            records_read = source_df.count()

            self.logger.info(
                "Source records counted | "
                f"run_id={run_id} | "
                f"records_read={records_read}"
            )

            # -------------------------------------------------
            # 8. Add Bronze metadata
            # -------------------------------------------------

            bronze_df = self._add_metadata(
                source_df=source_df,
                run_id=run_id,
                mode=mode
            )

            # -------------------------------------------------
            # 9. Replace processing window
            # -------------------------------------------------

            self._replace_processing_window(
                config=config,
                mode=mode,
                start_date=start_date,
                end_date=end_date
            )

            # -------------------------------------------------
            # 10. Write Bronze
            # -------------------------------------------------

            records_written = self._write_bronze(
                bronze_df=bronze_df,
                config=config
            )

            # -------------------------------------------------
            # 11. Audit SUCCESS
            # -------------------------------------------------

            end_time = datetime.now()

            self.audit_logger.log_run(
                run_id=run_id,
                request_id=request_id,
                pipeline_name=self.pipeline_name,
                layer=self.LAYER,
                operation=mode,
                status="SUCCESS",
                start_time=start_time,
                end_time=end_time,
                records_read=records_read,
                records_written=records_written,
                processing_start_date=start_date,
                processing_end_date=end_date,
                parameters={
                    "mode": mode,
                    "start_date": (
                        str(start_date)
                        if start_date else None
                    ),
                    "end_date": (
                        str(end_date)
                        if end_date else None
                    )
                }
            )

            self.logger.info(
                "Bronze ingestion completed successfully | "
                f"run_id={run_id} | "
                f"records_read={records_read} | "
                f"records_written={records_written}"
            )

            return {
                "run_id": run_id,
                "status": "SUCCESS",
                "records_read": records_read,
                "records_written": records_written
            }

        except Exception as exc:

            end_time = datetime.now()

            self.logger.exception(
                "Bronze ingestion failed | "
                f"run_id={run_id} | "
                f"request_id={request_id} | "
                f"error={str(exc)}"
            )

            try:

                self.audit_logger.log_run(
                    run_id=run_id,
                    request_id=request_id,
                    pipeline_name=self.pipeline_name,
                    layer=self.LAYER,
                    operation=mode,
                    status="FAILED",
                    start_time=start_time,
                    end_time=end_time,
                    records_read=records_read,
                    records_written=records_written,
                    processing_start_date=start_date,
                    processing_end_date=end_date,
                    parameters={
                        "mode": mode,
                        "start_date": (
                            str(start_date)
                            if start_date else None
                        ),
                        "end_date": (
                            str(end_date)
                            if end_date else None
                        )
                    },
                    error_message=str(exc)
                )

            except Exception:

                self.logger.exception(
                    "Failed to write Bronze FAILED audit record."
                )

            raise

    # ---------------------------------------------------------
    # CONFIGURATION
    # ---------------------------------------------------------

    def _get_pipeline_config(self):

        config = self.pipeline_config.get_config(
            pipeline_name=self.pipeline_name,
            layer=self.LAYER
        )

        self.logger.info(
            "Pipeline configuration resolved | "
            f"pipeline_name={config.pipeline_name} | "
            f"layer={config.layer} | "
            f"source_table={config.source_table} | "
            f"target_table={config.target_table} | "
            f"partition_column={config.partition_column} | "
            f"incremental_strategy="
            f"{config.incremental_strategy} | "
            f"write_strategy={config.write_strategy}"
        )

        return config

    # ---------------------------------------------------------
    # VALIDATION
    # ---------------------------------------------------------

    def _validate_parameters(
        self,
        mode,
        start_date,
        end_date
    ):

        if mode not in self.VALID_MODES:

            raise ValueError(
                f"Invalid processing mode: {mode}. "
                f"Allowed values: {self.VALID_MODES}"
            )

        # -----------------------------------------------------
        # BACKFILL requires explicit processing window
        # -----------------------------------------------------

        if mode == "BACKFILL":

            if start_date is None or end_date is None:

                raise ValueError(
                    "BACKFILL processing requires "
                    "start_date and end_date."
                )

        # -----------------------------------------------------
        # INITIAL does not require dates
        # -----------------------------------------------------

        if mode == "INITIAL":

            if start_date is not None or end_date is not None:

                self.logger.warning(
                    "INITIAL mode ignores start_date/end_date."
                )

        # -----------------------------------------------------
        # Validate date range when supplied
        # -----------------------------------------------------

        if (
            start_date is not None
            and end_date is not None
        ):

            if start_date > end_date:

                raise ValueError(
                    "start_date cannot be greater than end_date."
                )

    # ---------------------------------------------------------
    # PROCESSING WINDOW
    # ---------------------------------------------------------

    def _resolve_processing_window(
        self,
        config,
        mode,
        start_date=None,
        end_date=None
    ):

        # -----------------------------------------------------
        # INITIAL
        # -----------------------------------------------------

        if mode == "INITIAL":

            self.logger.info(
                "INITIAL mode: no processing window required."
            )

            return None, None

        # -----------------------------------------------------
        # BACKFILL
        # -----------------------------------------------------

        if mode == "BACKFILL":

            self.logger.info(
                "BACKFILL processing window resolved | "
                f"start_date={start_date} | "
                f"end_date={end_date}"
            )

            return start_date, end_date

        # -----------------------------------------------------
        # INCREMENTAL
        # -----------------------------------------------------

        if mode == "INCREMENTAL":

            window = (
                self.incremental_service
                .get_incremental_window(
                    pipeline_name=self.pipeline_name,
                    layer=self.LAYER
                )
            )

            if not window.has_data:

                self.logger.info(
                    "No incremental processing window available | "
                    f"pipeline_name={self.pipeline_name} | "
                    f"layer={self.LAYER}"
                )

                return None, None

            self.logger.info(
                "Incremental processing window resolved | "
                f"start_date={window.start_date} | "
                f"end_date={window.end_date}"
            )

            return (
                window.start_date,
                window.end_date
            )

        raise ValueError(
            f"Unsupported processing mode: {mode}"
        )

    # ---------------------------------------------------------
    # TABLE VALIDATION
    # ---------------------------------------------------------

    def _validate_tables(self, config):

        if not SparkUtils.validate_table_exists(
            self.spark,
            config.source_table
        ):

            raise ValueError(
                f"Source table does not exist: "
                f"{config.source_table}"
            )

        if not SparkUtils.validate_table_exists(
            self.spark,
            config.target_table
        ):

            raise ValueError(
                f"Bronze table does not exist: "
                f"{config.target_table}"
            )

        self.logger.info(
            "Source and Bronze tables validated | "
            f"source_table={config.source_table} | "
            f"target_table={config.target_table}"
        )

    # ---------------------------------------------------------
    # SOURCE READ
    # ---------------------------------------------------------

    def _read_source(
        self,
        config,
        mode,
        start_date,
        end_date
    ):

        source_df = self.spark.table(
            config.source_table
        )

        # -----------------------------------------------------
        # INITIAL
        # -----------------------------------------------------

        if mode == "INITIAL":

            self.logger.info(
                "INITIAL mode: reading entire source table | "
                f"source_table={config.source_table}"
            )

            return source_df

        # -----------------------------------------------------
        # INCREMENTAL / BACKFILL
        # -----------------------------------------------------

        partition_column = config.partition_column

        if not partition_column:

            raise ValueError(
                "Partition column is required for "
                f"{mode} processing | "
                f"pipeline_name={self.pipeline_name} | "
                f"layer={config.layer}"
            )

        self.logger.info(
            f"{mode} mode: reading source window | "
            f"source_table={config.source_table} | "
            f"partition_column={partition_column} | "
            f"start_date={start_date} | "
            f"end_date={end_date}"
        )

        return source_df.filter(
            (col(partition_column) >= start_date)
            & (col(partition_column) <= end_date)
        )

    # ---------------------------------------------------------
    # METADATA
    # ---------------------------------------------------------

    def _add_metadata(
        self,
        source_df,
        run_id,
        mode
    ):

        from pyspark.sql.functions import (
            current_timestamp,
            lit
        )

        return (
            source_df
            .withColumn(
                "ingestion_timestamp",
                current_timestamp()
            )
            .withColumn(
                "run_id",
                lit(run_id)
            )
            .withColumn(
                "processing_mode",
                lit(mode)
            )
        )

    # ---------------------------------------------------------
    # IDEMPOTENT REPLACEMENT
    # ---------------------------------------------------------

    def _replace_processing_window(
        self,
        config,
        mode,
        start_date,
        end_date
    ):

        target_table = config.target_table

        # -----------------------------------------------------
        # INITIAL
        # -----------------------------------------------------

        if mode == "INITIAL":

            self.logger.info(
                "INITIAL mode: clearing existing Bronze data | "
                f"target_table={target_table}"
            )

            self.spark.sql(
                f"""
                DELETE FROM {target_table}
                """
            )

            return

        # -----------------------------------------------------
        # INCREMENTAL / BACKFILL
        # -----------------------------------------------------

        partition_column = config.partition_column

        if not partition_column:

            raise ValueError(
                "Partition column is required for "
                f"{mode} replacement | "
                f"pipeline_name={self.pipeline_name} | "
                f"layer={config.layer}"
            )

        self.logger.info(
            "Replacing Bronze processing window | "
            f"target_table={target_table} | "
            f"partition_column={partition_column} | "
            f"start_date={start_date} | "
            f"end_date={end_date}"
        )

        self.spark.sql(
            f"""
            DELETE FROM {target_table}
            WHERE {partition_column} >= DATE('{start_date}')
              AND {partition_column} <= DATE('{end_date}')
            """
        )

    # ---------------------------------------------------------
    # WRITE
    # ---------------------------------------------------------

    def _write_bronze(
        self,
        bronze_df,
        config
    ):

        write_strategy = config.write_strategy

        self.logger.info(
            "Writing Bronze data | "
            f"target_table={config.target_table} | "
            f"write_strategy={write_strategy}"
        )

        if write_strategy == "APPEND":

            (
                bronze_df.write
                .format("delta")
                .mode("append")
                .saveAsTable(config.target_table)
            )

            records_written = bronze_df.count()

            self.logger.info(
                "Bronze write completed | "
                f"target_table={config.target_table} | "
                f"records_written={records_written}"
            )

            return records_written

        if write_strategy == "OVERWRITE":

            (
                bronze_df.write
                .format("delta")
                .mode("overwrite")
                .saveAsTable(config.target_table)
            )

            records_written = bronze_df.count()

            self.logger.info(
                "Bronze write completed | "
                f"target_table={config.target_table} | "
                f"records_written={records_written}"
            )

            return records_written

        raise ValueError(
            "Unsupported Bronze write strategy | "
            f"write_strategy={write_strategy}"
        )